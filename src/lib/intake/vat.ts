/**
 * Κανονικοποίηση και επικύρωση ελληνικού ΑΦΜ.
 *
 * Το ΑΦΜ είναι το κύριο κλειδί με το οποίο αντιστοιχίζουμε τα μέρη μιας
 * σύμβασης σε εγγραφές `Company`. Το OCR το επιστρέφει «βρόμικο», οπότε
 * καθαρίζεται πρώτα· το ψηφίο ελέγχου πιάνει σφάλματα ανάγνωσης πριν
 * αντιστοιχίσουμε λάθος εταιρία.
 *
 * Η `normalizeVat` καθαρίζει μια τιμή που ήδη θεωρούμε ΑΦΜ — ΔΕΝ είναι
 * ανιχνευτής που ψάχνει ΑΦΜ μέσα σε ελεύθερο κείμενο. Ένα οποιοδήποτε
 * 8-9ψήφιο σύνολο με διαχωριστικά (π.χ. μια ημερομηνία) περνάει τη μορφή
 * χωρίς πρόβλημα, οπότε όποιος αντιστοιχίζει σε πραγματικές εγγραφές
 * ΠΡΕΠΕΙ να περάσει το αποτέλεσμα και από `isValidGreekVat` πριν το
 * εμπιστευτεί ως κλειδί ταιριάσματος.
 */

/**
 * Ομόγραφα που το OCR συχνά διαβάζει αντί για ψηφία — λατινικά, ελληνικά
 * και κυριλλικά γράμματα που μοιάζουν οπτικά με 0/1/5/8. Καλύπτονται και
 * πεζά και κεφαλαία, γιατί τα σαρωμένα έγγραφα δίνουν εξίσου συχνά και τα
 * δύο.
 */
const LOOKALIKES: Record<string, string> = {
  O: "0", o: "0", // λατινικό O/o (U+004F, U+006F)
  Ο: "0", ο: "0", // ελληνικό Ο/ο (U+039F, U+03BF)
  о: "0", // κυριλλικό о (U+043E)
  I: "1", l: "1", "|": "1", // λατινικό I/l (U+0049, U+006C), κάθετος
  Ι: "1", ι: "1", // ελληνικό Ι/ι (U+0399, U+03B9)
  S: "5", Ѕ: "5", // λατινικό S (U+0053), κυριλλικό Ѕ (U+0405)
  B: "8", // λατινικό B (U+0042)
};

/** Ετικέτες που συνοδεύουν το ΑΦΜ στα έγγραφα. Αφαιρούνται μόνο από την αρχή. */
const LABEL = /^(Α\.?Φ\.?Μ\.?|AFM|VAT|TIN)\s*[:.\-]?\s*/i;

/** Διαχωριστικά που βάζουν οι άνθρωποι μέσα σε αριθμούς. */
const SEPARATORS = /[\s.\-/]/g;

/**
 * Καθαρίζει ένα ΑΦΜ σε 9 ψηφία, ή `null` αν δεν προκύπτει έγκυρο σχήμα.
 * Τα 8ψήφια (προ-1999) συμπληρώνονται με μπροστινό μηδέν.
 */
export function normalizeVat(raw: string | null | undefined): string | null {
  if (!raw) return null;

  // 1. Πρόθεμα χώρας ΠΡΙΝ τα ομόγραφα: το πεζό «l» του «el» θα γινόταν «1».
  const withoutPrefix = raw.trim().replace(/^(EL|GR)\s*/i, "");

  // 2. Ετικέτα («ΑΦΜ:») — έχει γράμματα, οπότε φεύγει πριν τον έλεγχο γραμμάτων.
  const withoutLabel = withoutPrefix.replace(LABEL, "");

  // 3. Ομόγραφα που το OCR διάβασε ως γράμματα.
  const folded = [...withoutLabel].map((ch) => LOOKALIKES[ch] ?? ch).join("");

  // 4. Διαχωριστικά.
  const compact = folded.replace(SEPARATORS, "");

  // 5. Ό,τι απέμεινε πρέπει να είναι ΜΟΝΟ ψηφία. Ένα άγνωστο γράμμα σημαίνει
  //    ότι δεν καταλάβαμε την είσοδο — καλύτερα null παρά ένα κλειδί που
  //    μοιάζει σωστό. Το ΑΦΜ αντιστοιχίζει συμβάσεις σε εταιρίες.
  if (!/^\d+$/.test(compact)) return null;

  if (compact.length === 8) return `0${compact}`;
  if (compact.length === 9) return compact;
  return null;
}

/**
 * Ψηφίο ελέγχου ελληνικού ΑΦΜ: τα πρώτα 8 ψηφία σταθμίζονται με 2^8…2^1,
 * το άθροισμα mod 11 mod 10 πρέπει να ισούται με το 9ο ψηφίο.
 *
 * Δέχεται ΜΟΝΟ ήδη κανονικοποιημένη είσοδο — κάλεσε πρώτα `normalizeVat`.
 */
export function isValidGreekVat(vat: string | null | undefined): boolean {
  if (!vat || !/^\d{9}$/.test(vat)) return false;
  if (vat === "000000000") return false;

  let sum = 0;
  for (let i = 0; i < 8; i++) {
    sum += Number(vat[i]) * 2 ** (8 - i);
  }
  return (sum % 11) % 10 === Number(vat[8]);
}
