import { describe, it, expect } from "vitest";
import { normalizeVat, isValidGreekVat } from "./vat";

describe("normalizeVat", () => {
  it("κρατά ένα καθαρό 9ψήφιο ΑΦΜ", () => {
    expect(normalizeVat("997939640")).toBe("997939640");
  });

  it.each([
    ["κενά", " 997 939 640 "],
    ["παύλες", "997-939-640"],
    ["τελείες", "997.939.640"],
    ["πρόθεμα EL", "EL997939640"],
    ["πρόθεμα el με κενό", "el 997939640"],
    ["πρόθεμα GR", "GR997939640"],
    ["ετικέτα ΑΦΜ", "ΑΦΜ: 997939640"],
  ])("καθαρίζει %s", (_label, input) => {
    expect(normalizeVat(input)).toBe("997939640");
  });

  it("συμπληρώνει μπροστινό μηδέν σε 8ψήφιο παλιό ΑΦΜ", () => {
    expect(normalizeVat("94014201")).toBe("094014201");
  });

  it.each([
    ["λατινικό O", "O", "0"],
    ["λατινικό o", "o", "0"],
    ["ελληνικό Ο", "Ο", "0"],
    ["ελληνικό ο", "ο", "0"],
    ["κυριλλικό о", "о", "0"],
    ["λατινικό I", "I", "1"],
    ["λατινικό l", "l", "1"],
    ["κάθετος |", "|", "1"],
    ["ελληνικό Ι", "Ι", "1"],
    ["ελληνικό ι", "ι", "1"],
    ["λατινικό S", "S", "5"],
    ["κυριλλικό Ѕ", "Ѕ", "5"],
    ["λατινικό B", "B", "8"],
  ])("διορθώνει ομόγραφο %s → %s", (_label, char, digit) => {
    expect(normalizeVat(`${char}97939640`)).toBe(`${digit}97939640`);
  });

  it.each([
    ["null", null],
    ["undefined", undefined],
    ["κενό", ""],
    ["μόνο γράμματα", "ΑΦΜ"],
    ["7 ψηφία", "1234567"],
    ["10 ψηφία", "1234567890"],
  ])("επιστρέφει null για %s", (_label, input) => {
    expect(normalizeVat(input as string)).toBeNull();
  });

  it.each([
    ["άγνωστο γράμμα στη μέση", "97Z939640"],
    ["άγνωστο γράμμα στην αρχή", "Z97939640"],
    ["σκέτο κείμενο", "ΣΥΜΒΑΣΗ"],
    ["επωνυμία εταιρίας", "DGSOFT"],
  ])("απορρίπτει είσοδο με άγνωστα γράμματα: %s", (_label, input) => {
    expect(normalizeVat(input)).toBeNull();
  });

  // Τεκμηριωμένο όριο, όχι σφάλμα: μια ημερομηνία είναι κι αυτή ψηφία με
  // διαχωριστικά, οπότε δεν ξεχωρίζει από ΑΦΜ ως προς τη μορφή. Η άμυνα είναι
  // ο έλεγχος ψηφίου ελέγχου στο σημείο αντιστοίχισης — βλ. company-match.ts,
  // που καλεί isValidGreekVat πριν δεχθεί ταίριασμα με ΑΦΜ.
  it("μια ημερομηνία μπορεί να μοιάζει με ΑΦΜ — γι' αυτό δεν αρκεί η κανονικοποίηση", () => {
    expect(normalizeVat("01/02/2026")).toBe("001022026");
    expect(isValidGreekVat("001022026")).toBe(true);
  });
});

describe("isValidGreekVat", () => {
  it.each(["997939640", "094014201"])("δέχεται έγκυρο ΑΦΜ %s", (vat) => {
    expect(isValidGreekVat(vat)).toBe(true);
  });

  it("απορρίπτει ΑΦΜ με λάθος ψηφίο ελέγχου", () => {
    expect(isValidGreekVat("997939641")).toBe(false);
  });

  it("απορρίπτει σκέτα μηδενικά", () => {
    expect(isValidGreekVat("000000000")).toBe(false);
  });

  it("απορρίπτει μη κανονικοποιημένη είσοδο", () => {
    expect(isValidGreekVat("997-939-640")).toBe(false);
  });

  it.each([null, undefined, "", "12345678"])("απορρίπτει %p", (input) => {
    expect(isValidGreekVat(input as string)).toBe(false);
  });
});
